import type { DesignSystem, NavItem, GhostThemeMeta, CustomThemeSetting, RoutingConfig } from './store';
import { serializeGhostFilter } from './ghost-filter';

interface PuckComponent {
  type: string;
  props: Record<string, unknown>;
}

interface PuckContent {
  content: PuckComponent[];
  root?: { props?: Record<string, unknown> };
  zones?: Record<string, PuckComponent[]>;
}

interface PageInput {
  name: string;
  slug: string;
  type: string;
  isHomepage: boolean;
  isCollection: boolean;
  collectionFilter: string;
  content: PuckContent;
}

interface ProjectInput {
  name: string;
  slug: string;
  designSystem: DesignSystem;
  navigation: NavItem[];
  themeSettings: Record<string, unknown>;
  customSettings: CustomThemeSetting[];
  routing: RoutingConfig;
  pages: PageInput[];
}

interface ThemeFile {
  path: string;
  content: string;
}

// ===== SUB-COMPILERS =====

function compilePackageJson(project: ProjectInput): string {
  const custom: Record<string, any> = {};
  for (const setting of project.customSettings) {
    custom[setting.key] = {
      type: setting.type,
      default: setting.default,
    };
    if (setting.options?.length && setting.type === 'select') {
      custom[setting.key].options = setting.options;
    }
    if (setting.group) {
      custom[setting.key].group = setting.group;
    }
  }

  return JSON.stringify({
    name: project.slug,
    description: `Ghost theme: ${project.name}`,
    version: "1.0.0",
    engines: { ghost: ">=5.0.0" },
    license: "MIT",
    author: { name: "Ghost Theme Builder" },
    config: {
      posts_per_page: (project.themeSettings?.postsPerPage as number) || 10,
      card_assets: true,
      custom,
    },
    keywords: ["ghost-theme"],
  }, null, 2);
}

function compileRoutesYaml(project: ProjectInput): string | null {
  const collections = project.routing?.collections || [];
  const taxonomies = project.routing?.taxonomies || { tag: '/tag/{slug}/', author: '/author/{slug}/' };

  // Only emit routes.yaml if there are custom collections
  if (collections.length === 0) return null;

  let yaml = `routes:\n  /: home\n\ncollections:\n`;
  for (const col of collections) {
    yaml += `  ${col.path}:\n`;
    yaml += `    permalink: ${col.permalink}\n`;
    yaml += `    template: ${col.template}\n`;
    if (col.filter) {
      yaml += `    filter: ${col.filter}\n`;
    }
  }

  yaml += `\ntaxonomies:\n`;
  yaml += `  tag: ${taxonomies.tag}\n`;
  yaml += `  author: ${taxonomies.author}\n`;

  return yaml;
}

function resolveStyleToken(value: string | undefined, tokenPath: string, ds: DesignSystem): string {
  if (!value) return '';
  const isEditable = ds.editableTokens?.includes(tokenPath);
  if (isEditable) {
    const key = tokenPath.replace('.', '_');
    return `var(--ghost-custom-${key}, ${value})`; // Fallback to value if custom var is missing
  }
  return value;
}

