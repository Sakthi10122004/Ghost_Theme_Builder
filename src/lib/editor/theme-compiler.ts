function generatePageTemplate(page: PageInput, _project: ProjectInput): { path: string; content: string } {
  const html = renderPageContent(page);

  if (page.type === "home" || page.isHomepage) {
    return {
      path: "index.hbs",
      content: `{{!< default}}\n{{!-- Home Page --}}\n${html}`,
    };
  }

  if (page.isCollection) {
    return {
      path: `${page.slug}.hbs`,
      content: `{{!< default}}\n{{!-- Collection: ${page.name} --}}\n${html}`,
    };
  }

  if (page.type === "blog") {
    return {
      path: "index.hbs",
      content: `{{!< default}}\n{{!-- Blog/Post Listing --}}\n${html}`,
    };
  }

  if (page.type === "post") {
    return { path: "post.hbs", content: `{{!< default}}\n${html}` };
  }

  // Custom pages
  return {
    path: `page-${page.slug}.hbs`,
    content: `{{!< default}}\n{{!-- ${page.name} --}}\n${html}`,
  };
}

