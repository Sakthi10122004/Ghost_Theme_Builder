function renderComponentHbs(comp: PuckComponent, zones?: Record<string, PuckComponent[]>): string {
  const p = comp.props;
  switch (comp.type) {
    case "Hero": {
      const children = zones?.[`${comp.props.id}:hero-content`] || [];
      const inner = children.map(c => renderComponentHbs(c, zones)).join("\n");
      return `<section class="hero" style="min-height:${p.minHeight || "500px"};background-color:${p.backgroundColor || "#0f172a"};${p.backgroundImage ? `background-image:url(${p.backgroundImage});background-size:cover;background-position:center;` : ""}display:flex;align-items:center;justify-content:center;padding:60px 24px;width:100%">
  <div class="hero-content" style="max-width:800px;width:100%;display:flex;flex-direction:column;align-items:center;text-align:center;gap:16px">
    ${inner}
  </div>
</section>`;
    }

    case "Section": {
      const children = zones?.[`${comp.props.id}:content`] || [];
      const inner = children.map(c => renderComponentHbs(c, zones)).join("\n");
      return `<section style="background-color:${p.backgroundColor || "transparent"};padding:${p.paddingY || "60px"} ${p.paddingX || "24px"};width:100%">
${inner}
</section>`;
    }

    case "Container": {
      const children = zones?.[`${comp.props.id}:content`] || [];
      const inner = children.map(c => renderComponentHbs(c, zones)).join("\n");
      return `<div class="container" style="max-width:${p.maxWidth || "1200px"};margin:0 auto;width:100%">
${inner}
</div>`;
    }

    case "Grid": {
      const children = zones?.[`${comp.props.id}:content`] || [];
      const inner = children.map(c => renderComponentHbs(c, zones)).join("\n");
      return `<div class="grid" style="display:grid;grid-template-columns:repeat(${p.columns || "3"},1fr);gap:${p.gap || "24px"};width:100%">
${inner}
</div>`;
    }

    case "Heading":
      return `<${p.level || "h2"} style="color:${p.color || "#1e293b"};${p.fontSize ? `font-size:${p.fontSize};` : ""}font-weight:${p.fontWeight || "700"};text-align:${p.textAlign || "left"};line-height:1.2">${p.text || "Heading"}</${p.level || "h2"}>`;

    case "Paragraph":
      return `<p style="color:${p.color || "#475569"};font-size:${p.fontSize || "16px"};text-align:${p.textAlign || "left"};line-height:${p.lineHeight || "1.7"};max-width:720px">${p.text || ""}</p>`;

    case "Image":
      return `<img src="${p.src || "{{@site.cover_image}}"}" alt="${p.alt || ""}" style="width:${p.width || "100%"};height:${p.height || "auto"};border-radius:${p.borderRadius || "8px"};object-fit:${p.objectFit || "cover"};display:block" />`;

    case "Button":
      return `<a href="${p.url || "#"}" class="btn btn-${p.variant || "primary"} btn-${p.size || "md"}" style="border-radius:${p.borderRadius || "8px"}">${p.text || "Button"}</a>`;

    case "Card": {
      const children = zones?.[`${comp.props.id}:card-content`] || [];
      const inner = children.map(c => renderComponentHbs(c, zones)).join("\n");
      return `<div class="card" style="background-color:${p.backgroundColor || "#ffffff"};border-radius:${p.borderRadius || "12px"};padding:${p.padding || "24px"};overflow:hidden;border:1px solid #e2e8f0">
  ${inner}
</div>`;
    }

    case "Divider":
      return `<hr style="border:none;border-top:${p.thickness || "1px"} ${p.style || "solid"} ${p.color || "#e2e8f0"};margin:${p.margin || "32px"} 0" />`;

    case "Spacer":
      return `<div style="height:${p.height || "40px"}"></div>`;

    case "Header": {
      const left = zones?.[`${comp.props.id}:header-left`] || [];
      const right = zones?.[`${comp.props.id}:header-right`] || [];
      return `<header class="site-header" style="background-color:${p.backgroundColor || "#ffffff"}">
  <div class="header-left">${left.map(c => renderComponentHbs(c, zones)).join("\n")}</div>
  <div class="header-right">${right.map(c => renderComponentHbs(c, zones)).join("\n")}</div>
</header>`;
    }

    case "Footer": {
      const children = zones?.[`${comp.props.id}:footer-content`] || [];
      return `<footer class="site-footer" style="background-color:${p.backgroundColor || "#0f172a"}">
  ${children.map(c => renderComponentHbs(c, zones)).join("\n")}
</footer>`;
    }

    // --- Ghost Dynamic ---
    case "GhostSiteTitle":
      return `<h1 class="site-title" style="color:${p.color || "#1e293b"};font-size:${p.fontSize || "24px"};font-weight:${p.fontWeight || "800"};margin:0;line-height:1.2"><a href="{{@site.url}}" style="color:inherit;text-decoration:none">{{@site.title}}</a></h1>`;

    case "GhostSiteDescription":
      return `<p class="site-description" style="color:${p.color || "#64748b"};font-size:${p.fontSize || "16px"};margin:0">{{@site.description}}</p>`;

    case "GhostSiteLogo":
      return `{{#if @site.logo}}<a href="{{@site.url}}"><img src="{{@site.logo}}" alt="{{@site.title}}" style="height:${p.height || "40px"};display:block" /></a>{{else}}<h2 style="font-size:24px;font-weight:700;margin:0"><a href="{{@site.url}}" style="text-decoration:none;color:inherit">{{@site.title}}</a></h2>{{/if}}`;

    case "GhostNavigation":
      return `{{navigation${p.isSecondary ? ' type="secondary"' : ''}}}`;

    case "GhostPostFeed": {
      const filterObj: Record<string, any> = {};
      if (p.tags) filterObj.tag = (p.tags as string).split(',').map(t => t.trim());
      if (p.featuredOnly) filterObj.featured = true;
      if (p.excludeId) filterObj.excludeId = true;
      const filterStr = serializeGhostFilter(filterObj);
      
      const limitStr = p.limit || "6";
      
      return `<div class="post-feed" style="display:grid;grid-template-columns:repeat(${p.postsPerRow || "3"},1fr);gap:24px">
  {{#get "posts" limit="${limitStr}"${filterStr ? ` filter="${filterStr}"` : ""}}}
    {{#foreach posts}}
      {{> "post-card"}}
    {{/foreach}}
  {{else}}
    <p>No posts found.</p>
  {{/get}}
</div>`;
    }

    case "GhostAuthor":
      return `{{#author}}
<div class="author-profile" style="text-align:center;padding:24px;border:1px solid #e2e8f0;border-radius:8px">
  {{#if profile_image}}<img src="{{profile_image}}" alt="{{name}}" style="width:80px;height:80px;border-radius:50%;margin:0 auto 16px" />{{/if}}
  <h3 style="font-size:18px;font-weight:700;margin:0 0 8px 0">{{name}}</h3>
  {{#if bio}}<p style="font-size:14px;color:#64748b;max-width:300px;margin:0 auto">{{bio}}</p>{{/if}}
</div>
{{/author}}`;

    case "GhostTags":
      return `<div class="tags" style="display:flex;gap:8px;flex-wrap:wrap">
  {{tags separator="" autolink="true" class="tag-pill"}}
</div>`;

    case "GhostPagination":
      return `<div class="pagination" style="display:flex;justify-content:center;padding:32px 0">
  {{pagination}}
</div>`;

    case "GhostSubscribe":
      return `<div class="subscribe-section" style="padding:24px;border:1px solid #e2e8f0;border-radius:8px;background:#f8fafc">
  <form data-members-form="subscribe" style="display:flex;gap:8px">
    <input data-members-email type="email" required placeholder="Your email address" style="padding:10px 16px;border:1px solid #cbd5e1;border-radius:6px;width:100%;max-width:240px" />
    <button type="submit" style="padding:10px 20px;background:${p.buttonColor || "#4f46e5"};color:white;border:none;border-radius:6px;font-weight:600;cursor:pointer">Subscribe</button>
  </form>
</div>`;

    case "GhostPostContent":
      return `<div class="post-content">
  {{content}}
</div>`;

    case "GhostPostTitle":
      return `<h1 style="color:${p.color || "#1e293b"};font-size:${p.fontSize || "36px"};font-weight:${p.fontWeight || "800"};margin:0;line-height:1.2">{{title}}</h1>`;

    case "GhostPostDate":
      return `<span style="color:${p.color || "#64748b"};font-size:${p.fontSize || "14px"}">{{date format="MMMM DD, YYYY"}}</span>`;

    case "GhostPostFeatureImage":
      return `{{#if feature_image}}
<img src="{{feature_image}}" alt="{{title}}" style="width:100%;height:auto;border-radius:${p.borderRadius || "8px"};display:block" />
{{/if}}`;

    default:
      return `<!-- Unknown component: ${comp.type} -->`;
  }
}

// ===== MAIN COMPILER =====

export function compileTheme(project: ProjectInput): ThemeFile[] {
  const files: ThemeFile[] = [];
  const ds = project.designSystem;

  // 1. package.json
  files.push({
    path: "package.json",
    content: compilePackageJson(project),
  });

  // 2. routes.yaml
  const routesYaml = compileRoutesYaml(project);
  if (routesYaml) {
    files.push({ path: "routes.yaml", content: routesYaml });
  }

  // 3. CSS
  const css = compileCSS(ds);
  files.push({ path: "assets/css/theme.css", content: css });

  // 4. JS
  files.push({ path: "assets/js/theme.js", content: generateJS() });

  // 5. default.hbs
  files.push({ path: "default.hbs", content: generateDefaultHbs(project) });

  // 6. Partials
  files.push({ path: "partials/header.hbs", content: generateHeaderPartial(project) });
  files.push({ path: "partials/footer.hbs", content: generateFooterPartial(project) });
  files.push({ path: "partials/navigation.hbs", content: generateNavigationPartial() });
  files.push({ path: "partials/post-card.hbs", content: generatePostCardPartial() });

  // 7. Page templates
  for (const page of project.pages) {
    const { path, content } = generatePageTemplate(page, project);
    files.push({ path, content });
  }

  // 8. Required Ghost templates (if not already created)
  const existingPaths = new Set(files.map(f => f.path));
  if (!existingPaths.has("index.hbs")) {
    files.push({ path: "index.hbs", content: generateIndexFallback() });
  }
  if (!existingPaths.has("post.hbs")) {
    files.push({ path: "post.hbs", content: generatePostTemplate() });
  }
  if (!existingPaths.has("page.hbs")) {
    files.push({ path: "page.hbs", content: generateGenericPageTemplate() });
  }
  files.push({ path: "tag.hbs", content: generateTagTemplate() });
  files.push({ path: "author.hbs", content: generateAuthorTemplate() });
  files.push({ path: "error.hbs", content: generateErrorTemplate() });

  return files;
}

function renderPageContent(page: PageInput): string {
  const content = page.content as PuckContent;
  if (!content?.content?.length) return "<p>This page is empty.</p>";
  return content.content.map(c => renderComponentHbs(c, content.zones)).join("\n\n");
}

function generateDefaultHbs(project: ProjectInput): string {
  let customStyleBlock = '';
  if (project.designSystem.editableTokens && project.designSystem.editableTokens.length > 0) {
    customStyleBlock = `\n  <style>\n    :root {\n`;
    for (const token of project.designSystem.editableTokens) {
      const key = token.replace('.', '_');
      customStyleBlock += `      --ghost-custom-${key}: {{@custom.${key}}};\n`;
    }
    customStyleBlock += `    }\n  </style>\n`;
  }

  return `<!DOCTYPE html>
<html lang="{{@site.locale}}">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>{{meta_title}}</title>
  <link rel="stylesheet" href="{{asset "css/theme.css"}}" />${customStyleBlock}
  {{ghost_head}}
</head>
<body class="{{body_class}}">
  {{{body}}}
  <script src="{{asset "js/theme.js"}}"></script>
  {{ghost_foot}}
</body>
</html>`;
}

function generateJS(): string {
  return `// Ghost Theme JS - Generated by Ghost Theme Builder
(function() {
  // Mobile menu toggle
  const menuToggle = document.querySelector('.menu-toggle');
  const navList = document.querySelector('.nav-list');
  if (menuToggle && navList) {
    menuToggle.addEventListener('click', () => navList.classList.toggle('is-open'));
  }
})();`;
}

